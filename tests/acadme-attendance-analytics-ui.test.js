'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
const page=read('views/attendance/analytics.ejs');
const css=read('public/css/acadme-attendance-analytics.css');
const header=read('views/partials/header.ejs');
const pkg=JSON.parse(read('package.json'));
assert.ok(page.includes('attendance-analytics-page'));
assert.ok(!/<style[\\s>]/i.test(page),'Embedded style block remains');
ejs.compile(page,{filename:'views/attendance/analytics.ejs'});
for(const field of ['section_id','name="session"','name="term"','name="class_id"','dashboard.overview','dashboard.classComparison','dashboard.dailySummary','dashboard.lowAttendanceStudents','dashboard.topLateStudents','overview.attendanceRate','overview.leaveDays']) assert.ok(page.includes(field),'Analytics contract missing '+field);
for(const status of ['Present','Late','Absent','Leave']) assert.ok(page.includes(status),'Attendance status missing '+status);
assert.ok(page.includes('this.form.submit()'),'Existing filter auto-submit behavior missing');
assert.ok(header.includes('acadme-attendance-analytics.css'));
assert.equal(pkg.scripts['test:acadme-attendance-analytics-ui'],'node tests/acadme-attendance-analytics-ui.test.js');
const tokens=new Set([...read('public/css/acadme-tokens.css').matchAll(/(--acm-[\\w-]+)\\s*:/g)].map(m=>m[1]));
for(const m of css.matchAll(/var\\((--acm-[\\w-]+)/g)) assert.ok(tokens.has(m[1]),'Undefined token '+m[1]);
assert.ok(css.includes('@media (max-width:600px)'));
console.log('AcadMe attendance analytics UI source checks passed.');
