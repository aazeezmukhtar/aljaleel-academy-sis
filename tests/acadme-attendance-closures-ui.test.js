'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=file=>fs.readFileSync(path.join(__dirname,'..',file),'utf8');
const header=read('views/partials/header.ejs');
assert.ok(header.indexOf('acadme-attendance-closures.css')>header.indexOf('acadme-attendance.css'),'Closures stylesheet must load after attendance styles');
const css=read('public/css/acadme-attendance-closures.css');
const tokens=new Set([...read('public/css/acadme-tokens.css').matchAll(/(--acm-[\w-]+)\s*:/g)].map(m=>m[1]));
for(const m of css.matchAll(/var\((--acm-[\w-]+)/g))assert.ok(tokens.has(m[1]),'Undefined AcadMe token: '+m[1]);
assert.match(css,/@media\(max-width:640px\)/);
assert.match(css,/prefers-reduced-motion:reduce/);
const file='views/attendance/closures.ejs',source=read(file);
assert.match(source,/attendance-closures-page/);
assert.doesNotMatch(source,/<style>/);
assert.doesNotThrow(()=>ejs.compile(source,{filename:path.join(__dirname,'..',file)}));
for(const item of ['id="closure-request-form"','name="scope_type"','name="section_id"','name="class_id"','name="start_date"','name="end_date"','name="reason"','/attendance/closures/request','/attendance/closures/decide','/attendance/closures/cancel','data-closure-action="approved"','data-closure-action="rejected"','data-cancel-closure'])assert.ok(source.includes(item),'Existing closure behavior missing '+item);
assert.match(source,/isAdmin && item\.status === 'pending'/);
assert.match(source,/item\.status === 'pending' && \(isAdmin/);
console.log('AcadMe Attendance Closures UI presentation checks passed.');
