'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=file=>fs.readFileSync(path.join(__dirname,'..',file),'utf8');
const page=read('views/reports/attendance/daily.ejs');
const css=read('public/css/acadme-attendance-daily-report.css');
const header=read('views/partials/header.ejs');
const tokens=read('public/css/acadme-tokens.css');
assert.match(page,/attendance-daily-report-page/);
assert.doesNotMatch(page,/<style>|style="/);
assert.match(page,/action="\/reports\/attendance\/daily" method="GET"/);
for(const field of ['date','type','class_id'])assert.match(page,new RegExp('name="'+field+'"'));
assert.match(page,/window\.print\(\)/);
assert.match(page,/exportTableToCSV\('daily-attendance-/);
assert.match(page,/id="dataTable"/);
assert.match(page,/students\.forEach/);
assert.match(page,/students\.length/);
assert.ok(header.indexOf('acadme-attendance-daily-report.css')>header.indexOf('acadme-attendance-report.css'));
for(const selector of ['.attendance-daily-header','.attendance-daily-filter-form','.attendance-daily-table-wrap','.attendance-daily-empty'])assert.ok(css.includes(selector));
const defined=new Set([...tokens.matchAll(/(--acm-[\w-]+)\s*:/g)].map(m=>m[1]));
for(const m of css.matchAll(/var\((--acm-[\w-]+)/g))assert.ok(defined.has(m[1]),'Undefined token '+m[1]);
ejs.compile(page,{filename:path.join(__dirname,'..','views/reports/attendance/daily.ejs')});
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.scripts['test:acadme-attendance-daily-report-ui'],'node tests/acadme-attendance-daily-report-ui.test.js');
console.log('Daily attendance report UI source checks passed.');
