'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
const page=read('views/attendance/operations.ejs');
const css=read('public/css/acadme-attendance-operations.css');
const header=read('views/partials/header.ejs');
const pkg=JSON.parse(read('package.json'));
ejs.compile(page,{filename:'views/attendance/operations.ejs'});
assert.ok(page.includes('attendance-operations-page'));
assert.ok(header.includes('acadme-attendance-operations.css'));
assert.equal(pkg.scripts['test:acadme-attendance-operations-ui'],'node tests/acadme-attendance-operations-ui.test.js');
for(const field of ['operations.summary.expected','operations.summary.submitted','operations.summary.incomplete','operations.summary.missing','operations.summary.overdue','operations.schedulerHistory','operations.notificationDeliveryHealth','operations.rows','operations.recentFailures','reminder.acknowledgedAt','This page is read-only']) assert.ok(page.includes(field),'Operations contract missing '+field);
for(const status of ['Submitted','Missing','Overdue','Incomplete','Succeeded','Failed','Possibly interrupted','Running']) assert.ok(page.includes(status),'Status label missing '+status);
assert.ok(page.includes('Africa/Lagos'),'Nigeria timezone formatting missing');
const tokens=new Set([...read('public/css/acadme-tokens.css').matchAll(/(--acm-[\w-]+)\s*:/g)].map(m=>m[1]));
for(const m of css.matchAll(/var\((--acm-[\w-]+)/g)) assert.ok(tokens.has(m[1]),'Undefined token '+m[1]);
assert.ok(css.includes('@media(max-width:700px)'));
console.log('AcadMe attendance operations UI source checks passed.');
