'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
const low=read('views/reports/attendance/low.ejs');
const register=read('views/reports/attendance/register.ejs');
const css=read('public/css/acadme-attendance-register-reports.css');
const header=read('views/partials/header.ejs');
const pkg=JSON.parse(read('package.json'));
assert.ok(low.includes('attendance-low-report-page'));
assert.ok(register.includes('attendance-monthly-register-page'));
assert.ok(!/<style[\s>]/i.test(low)&&!/<style[\s>]/i.test(register),'Inline styles remain');
ejs.compile(low,{filename:'views/reports/attendance/low.ejs'});
ejs.compile(register,{filename:'views/reports/attendance/register.ejs'});
for(const field of ['query.term','query.session','query.threshold','availableSessions','available_sessions','student.present_days','student.total_days'])assert.ok(low.includes(field),'Low attendance contract missing '+field);
for(const route of ['/reports/attendance/low','/reports/attendance/register'])assert.ok((low+register).includes(route),'Filter destination missing '+route);
for(const field of ['query.class_id','query.month','query.year','registerData.days','registerData.students','student.attendance[day]','student.summary.present','student.summary.absent','student.summary.late'])assert.ok(register.includes(field),'Register contract missing '+field);
for(const filename of ['low_attendance.csv','attendance_register.csv'])assert.ok((low+register).includes(filename),'CSV filename missing '+filename);
assert.ok((low+register).includes('window.print()'),'Print action missing');
assert.ok(header.includes('acadme-attendance-register-reports.css'));
assert.equal(pkg.scripts['test:acadme-attendance-register-reports-ui'],'node tests/acadme-attendance-register-reports-ui.test.js');
const tokens=new Set([...read('public/css/acadme-tokens.css').matchAll(/(--acm-[\w-]+)\s*:/g)].map(m=>m[1]));
for(const m of css.matchAll(/var\((--acm-[\w-]+)/g))assert.ok(tokens.has(m[1]),'Undefined token '+m[1]);
assert.ok(css.includes('@media print'));
assert.ok(css.includes('@media(max-width:640px)'));
console.log('AcadMe attendance register reports UI source checks passed.');
