'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=file=>fs.readFileSync(path.join(__dirname,'..',file),'utf8');
const header=read('views/partials/header.ejs');
const tokensAt=header.indexOf('acadme-tokens.css'),sharedAt=header.indexOf('acadme-components.css'),attendanceAt=header.indexOf('acadme-attendance.css'),reportAt=header.indexOf('acadme-attendance-report.css');
assert.ok(tokensAt>=0&&sharedAt>tokensAt&&attendanceAt>sharedAt&&reportAt>attendanceAt,'Attendance report styles must load after shared and Attendance styles');
const page=read('views/attendance/report.ejs');
assert.match(page,/attendance-report-page/);
assert.doesNotMatch(page,/<style>|style="/,'Attendance report styles must be external and scoped');
assert.match(page,/action="\/attendance\/report" method="GET"/);
for(const field of ['class_id','start_date','end_date'])assert.match(page,new RegExp('name="'+field+'"'));
for(const expression of ['reportData.forEach','row.attendanceRate === null','row.attendanceRate.toFixed(1)','row.belowThreshold','reportMeta.threshold','reportMeta.registerCompletion'])assert.ok(page.includes(expression),'Preserve report expression: '+expression);
for(const name of ['attendance-report-value--present','attendance-report-value--late','attendance-report-value--absent','attendance-report-value--leave','attendance-report-index--below','attendance-report-index--healthy'])assert.ok(page.includes(name),'Missing semantic presentation class: '+name);
ejs.compile(page,{filename:path.join(__dirname,'..','views/attendance/report.ejs')});
const css=read('public/css/acadme-attendance-report.css');
for(const selector of ['.attendance-report-filter-grid','.attendance-report-summary','.attendance-report-table-wrap','.attendance-report-empty'])assert.ok(css.includes(selector),'Missing report styling: '+selector);
assert.match(css,/max-width:699px|@media\(max-width:699px\)/);
assert.match(css,/prefers-reduced-motion/);
const tokenSource=read('public/css/acadme-tokens.css');
const defined=new Set([...tokenSource.matchAll(/(--acm-[\w-]+)\s*:/g)].map(m=>m[1]));
for(const match of css.matchAll(/var\((--acm-[\w-]+)/g))assert.ok(defined.has(match[1]),'Undefined AcadMe token: '+match[1]);
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.scripts['test:acadme-attendance-report-ui'],'node tests/acadme-attendance-report-ui.test.js');
console.log('AcadMe Attendance Report UI source checks passed.');
