'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=file=>fs.readFileSync(path.join(__dirname,'..',file),'utf8');
const header=read('views/partials/header.ejs');
assert.ok(header.indexOf('acadme-attendance-setup.css')>header.indexOf('acadme-attendance.css'),'Setup stylesheet must load after attendance styles');
const css=read('public/css/acadme-attendance-setup.css');
const tokens=new Set([...read('public/css/acadme-tokens.css').matchAll(/(--acm-[\w-]+)\s*:/g)].map(m=>m[1]));
for(const m of css.matchAll(/var\((--acm-[\w-]+)/g))assert.ok(tokens.has(m[1]),'Undefined AcadMe token: '+m[1]);
assert.match(css,/@media\(max-width:640px\)/);
assert.match(css,/prefers-reduced-motion:reduce/);
const file='views/attendance/setup.ejs',source=read(file);
assert.match(source,/attendance-setup-page/);
assert.doesNotThrow(()=>ejs.compile(source,{filename:path.join(__dirname,'..',file)}));
for(const action of ['academic_period','section_schedule','class_schedule','responsibility','settings'])assert.ok(source.includes('data-action="'+action+'"'),'Missing setup action '+action);
for(const field of ['sectionId','session','term','startDate','endDate','effectiveFrom','effectiveTo','weekdays','classId','responsibilityType','staffId','deadline','firstReminderDelayMinutes','lowAttendanceThreshold','subsequentReminderIntervals'])assert.ok(source.includes('name="'+field+'"'),'Missing setup field '+field);
for(const endpoint of ['/attendance/setup/save'])assert.ok(source.includes(endpoint));
for(const selector of ['.setup-form','[data-end]','data-end="schedule-set"','data-end="academic_period"','data-end="responsibility"','data-end="settings"','setup.scheduleFoundationAvailable','setup.readinessSummary'])assert.ok(source.includes(selector),'Existing setup behavior missing '+selector);
assert.match(source,/formData\.getAll\('weekdays'\)/);
assert.match(source,/end_schedule_set/);
assert.match(source,/Intl\.DateTimeFormat\('en-GB'.*Africa\/Lagos/);
console.log('AcadMe Attendance Setup UI presentation checks passed.');
