const assert = require('assert');
const fs = require('fs');
const path = require('path');
const ejs = require('ejs');
const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const header = read('views/partials/header.ejs');
assert(header.indexOf('/css/acadme-auth.css') > header.indexOf('/css/acadme-settings.css'), 'Auth stylesheet must load after shared UI layers');
const css = read('public/css/acadme-auth.css');
for (const value of ['max-width:640px', 'prefers-reduced-motion', ':focus-visible', 'min-height:48px']) assert(css.includes(value), 'Missing auth accessibility/mobile rule: ' + value);
const staffLogin = read('views/auth/login.ejs');
assert(staffLogin.includes('acadme-staff-login-page'), 'Staff login scope missing');
assert(staffLogin.includes('action="/auth/login"') && staffLogin.includes('name="staff_id"') && staffLogin.includes('name="password"'), 'Staff login contract changed');
assert(staffLogin.includes('togglePwd()'), 'Password visibility control missing');
assert(!/<style[\s>]/i.test(staffLogin), 'Staff login presentation must live in the shared auth stylesheet');
assert(!/\sstyle=/.test(staffLogin), 'Staff login must not retain inline presentation styles');
assert(css.includes('.acadme-staff-login-page.login-page') && css.includes('.acadme-login-submit'), 'Staff login styles must be scoped in AcadMe auth CSS');
ejs.compile(staffLogin, { filename: path.join(root, 'views/auth/login.ejs') });
const password = read('views/auth/change_password.ejs');
assert(password.includes('acadme-password-settings-page') && password.includes('acadme-password-settings-main'), 'Password settings scopes missing');
assert(password.includes('action="/auth/change-password"'), 'Password update action changed');
for (const field of ['current_password', 'new_password', 'confirm_password']) assert(password.includes('name="' + field + '"'), 'Password field missing: ' + field);
ejs.compile(password, { filename: path.join(root, 'views/auth/change_password.ejs') });
console.log('AcadMe authentication UI source checks passed.');
