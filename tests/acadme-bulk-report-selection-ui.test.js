'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=file=>fs.readFileSync(path.join(__dirname,'..',file),'utf8');
const header=read('views/partials/header.ejs');
const resultsAt=header.indexOf('acadme-results.css');
const featureAt=header.indexOf('acadme-bulk-report-selection.css');
assert.ok(resultsAt>=0&&featureAt>resultsAt,'Bulk report selection styles must load after Results styles');
const page=read('views/results/bulk_select.ejs');
assert.match(page,/results-bulk-select-page/);
assert.doesNotMatch(page,/<style>|style="/,'Page presentation must be external');
assert.match(page,/id="bulkReportForm" method="GET" action="\/results\/bulk"/);
for(const field of ['class_id','term','session'])assert.match(page,new RegExp('name="'+field+'"'));
assert.match(page,/user\.role === 'Admin'/);
assert.match(page,/onclick="publishBulk\(\)"/);
assert.match(page,/fetch\('\/results\/publish-bulk'/);
assert.match(page,/JSON\.stringify\(\{ class_id, term, session \}\)/);
assert.match(page,/availableSessions/);
assert.match(page,/available_sessions/);
ejs.compile(page,{filename:path.join(__dirname,'..','views/results/bulk_select.ejs')});
const css=read('public/css/acadme-bulk-report-selection.css');
for(const selector of ['.results-bulk-card','.results-bulk-field','.results-bulk-actions','.results-bulk-publish'])assert.ok(css.includes(selector),'Missing selector '+selector);
assert.match(css,/max-width:640px/);
assert.match(css,/prefers-reduced-motion/);
const tokenSource=read('public/css/acadme-tokens.css');
const defined=new Set([...tokenSource.matchAll(/(--acm-[\w-]+)\s*:/g)].map(m=>m[1]));
for(const match of css.matchAll(/var\((--acm-[\w-]+)/g))assert.ok(defined.has(match[1]),'Undefined AcadMe token: '+match[1]);
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.scripts['test:acadme-bulk-report-selection-ui'],'node tests/acadme-bulk-report-selection-ui.test.js');
console.log('AcadMe bulk report selection UI source checks passed.');
