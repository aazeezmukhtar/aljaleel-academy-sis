'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=file=>fs.readFileSync(path.join(__dirname,'..',file),'utf8');
const header=read('views/partials/header.ejs');
const layers=['acadme-tokens.css','acadme-components.css','acadme-shells.css','acadme-students.css','acadme-attendance.css','acadme-results.css','acadme-finance.css','acadme-academics.css','acadme-staff.css','acadme-reports.css','acadme-announcements.css','acadme-calendar.css'].map(x=>header.indexOf(x));
assert.ok(layers.every((v,i)=>v>=0&&(i===0||v>layers[i-1])),'Calendar stylesheet must follow the shared Admin/Staff layers');
const portalHead=read('views/partials/student_shell_head.ejs');
assert.ok(portalHead.indexOf('student-portal-modern.css')<portalHead.indexOf('acadme-calendar.css'),'Calendar stylesheet must follow the student shell');
const css=read('public/css/acadme-calendar.css');
const tokens=new Set([...read('public/css/acadme-tokens.css').matchAll(/(--acm-[\w-]+)\s*:/g)].map(m=>m[1]));
for(const m of css.matchAll(/var\((--acm-[\w-]+)/g))assert.ok(tokens.has(m[1]),'Undefined AcadMe token: '+m[1]);
assert.match(css,/@media\(max-width:760px\)/);
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
const index=read('views/calendar/index.ejs');
assert.match(index,/calendar-list-page/);
for(const value of ['Manage Calendar','event.title','event.description','event.type','event.term','event.session','event.section_name','No Events Scheduled'])assert.ok(index.includes(value),'Calendar display missing '+value);
ejs.compile(index,{filename:path.join(__dirname,'..','views/calendar/index.ejs')});
const manage=read('views/calendar/manage.ejs');
assert.match(manage,/calendar-manage-page/);
for(const field of ['name="title"','name="event_date"','name="type"','name="section_id"','name="session"','name="term"','name="description"'])assert.ok(manage.includes(field),'Existing calendar field missing '+field);
for(const action of ['/calendar/add','/calendar/delete/<%= event.id %>','/calendar'])assert.ok(manage.includes(action),'Existing calendar action missing '+action);
assert.match(manage,/confirm\('Delete this event\?'\)/);
ejs.compile(manage,{filename:path.join(__dirname,'..','views/calendar/manage.ejs')});
const portal=read('views/portal/calendar.ejs');
assert.match(portal,/portal-calendar-page/);
for(const value of ['event.event_date','event.title','event.description','event.type','No upcoming events'])assert.ok(portal.includes(value),'Student calendar content missing '+value);
ejs.compile(portal,{filename:path.join(__dirname,'..','views/portal/calendar.ejs')});
console.log('AcadMe Calendar UI presentation checks passed.');
