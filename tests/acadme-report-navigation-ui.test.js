'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
const center=read('views/reports/index.ejs');
const attendance=read('views/reports/attendance/index.ejs');
const css=read('public/css/acadme-report-navigation.css');
const header=read('views/partials/header.ejs');
assert.ok(center.includes('reports-center-page'));
assert.ok(attendance.includes('reports-attendance-page'));
assert.ok(!/<style[\s>]/i.test(center)&&!/<style[\s>]/i.test(attendance),'Inline styles remain');
ejs.compile(center,{filename:'views/reports/index.ejs'});
ejs.compile(attendance,{filename:'views/reports/attendance/index.ejs'});
for(const route of ['/reports/academic','/reports/students','/reports/attendance','/reports/fees','/reports/staff','/reports/health','/reports/audit'])assert.ok(center.includes(route),'Report destination missing '+route);
for(const roleRule of ["user.role==='Admin' || user.role==='Bursar'","user.role==='Admin'"])assert.ok(center.includes(roleRule),'Role visibility condition missing');
for(const route of ['/reports/attendance/register','/reports/attendance/low'])assert.ok(attendance.includes(route),'Attendance report destination missing '+route);
for(const field of ['stats.present_today','stats.absent_today','stats.late_today'])assert.ok(attendance.includes(field),'Attendance summary field missing '+field);
assert.ok(header.includes('acadme-report-navigation.css'));
const tokens=new Set([...read('public/css/acadme-tokens.css').matchAll(/(--acm-[\w-]+)\s*:/g)].map(m=>m[1]));
for(const m of css.matchAll(/var\((--acm-[\w-]+)/g))assert.ok(tokens.has(m[1]),'Undefined token '+m[1]);
assert.ok(css.includes('@media(max-width:600px)'));
console.log('AcadMe report navigation UI source checks passed.');
