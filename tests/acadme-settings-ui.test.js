'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
const header=read('views/partials/header.ejs');
const layers=['acadme-tokens.css','acadme-components.css','acadme-shells.css','acadme-students.css','acadme-attendance.css','acadme-results.css','acadme-finance.css','acadme-academics.css','acadme-staff.css','acadme-reports.css','acadme-announcements.css','acadme-calendar.css','acadme-settings.css'].map(x=>header.indexOf(x));
assert.ok(layers.every((v,i)=>v>=0&&(i===0||v>layers[i-1])),'Settings stylesheet order is incorrect');
const css=read('public/css/acadme-settings.css');
const tokens=new Set([...read('public/css/acadme-tokens.css').matchAll(/(--acm-[\w-]+)\s*:/g)].map(m=>m[1]));
for(const m of css.matchAll(/var\((--acm-[\w-]+)/g))assert.ok(tokens.has(m[1]),'Undefined token '+m[1]);
assert.match(css,/@media\(max-width:760px\)/);
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
const settings=read('views/settings.ejs');
assert.match(settings,/school-settings-page/);
for(const field of ['name="school_name"','name="school_motto"','name="school_logo"','name="primary_color"','name="secondary_color"','name="address"','name="phone"','name="current_session"','name="current_term"','name="next_term_start_date"','name="show_watermark"','name="attendance_term_absence_limit"','name="attendance_consecutive_absence_limit"','action="/settings/section-calendar"','/settings/promotion'])assert.ok(settings.includes(field),'Settings control missing '+field);
assert.match(settings,/enctype="multipart\/form-data"/);
ejs.compile(settings,{filename:path.join(__dirname,'..','views/settings.ejs')});
const promotion=read('views/settings/promotion.ejs');
assert.match(promotion,/promotion-page/);
for(const value of ['name="source_session"','name="target_session"','mapping[<%= cls.id %>]','commencement-','previewBtn','fetchPreview()','setPromotionSelection(true)','setPromotionSelection(false)','confirmPromotion()','commitBtn','promotionWarnings','promotionTotals'])assert.ok(promotion.includes(value),'Promotion workflow element missing '+value);
assert.match(promotion,/Section protection is active/);
ejs.compile(promotion,{filename:path.join(__dirname,'..','views/settings/promotion.ejs')});
console.log('AcadMe Settings UI presentation checks passed.');
