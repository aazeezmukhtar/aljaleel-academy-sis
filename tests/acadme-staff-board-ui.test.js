'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=file=>fs.readFileSync(path.join(__dirname,'..',file),'utf8');
const header=read('views/partials/header.ejs');
assert.ok(header.indexOf('acadme-staff-board.css')>header.indexOf('acadme-staff.css'),'Staff board styles must load after staff feature styles');
const css=read('public/css/acadme-staff-board.css');
const tokens=new Set([...read('public/css/acadme-tokens.css').matchAll(/(--acm-[\w-]+)\s*:/g)].map(m=>m[1]));
for(const m of css.matchAll(/var\((--acm-[\w-]+)/g))assert.ok(tokens.has(m[1]),'Undefined AcadMe token: '+m[1]);
assert.match(css,/@media\(max-width:760px\)/);
assert.match(css,/prefers-reduced-motion:reduce/);
const file='views/staff/board.ejs',source=read(file);
assert.match(source,/staff-class-board-page/);
assert.doesNotThrow(()=>ejs.compile(source,{filename:path.join(__dirname,'..',file)}));
for(const item of ['action="/staff/board/post"','enctype="multipart/form-data"','name="class_id"','name="subject_id"','name="student_id"','name="post_type"','name="due_date"','name="title"','name="content"','name="attachment"','/staff/board/post/delete/','filterStudents()','postTypeSelect'])assert.ok(source.includes(item),'Existing class board feature missing '+item);
assert.match(source,/confirm\('Are you sure you want to delete this post\?'/);
console.log('AcadMe Staff Class Board UI presentation checks passed.');
