'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ejs=require('ejs');
const read=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
const page=read('views/reports/audit.ejs');
const css=read('public/css/acadme-system-audit.css');
const header=read('views/partials/header.ejs');
const pkg=read('package.json');
assert.ok(page.includes('system-audit-page'),'Audit page scope missing');
assert.ok(!/<style[\\s>]/i.test(page),'Embedded styles remain');
ejs.compile(page,{filename:path.join(__dirname,'..','views/reports/audit.ejs')});
assert.ok(header.indexOf('acadme-system-audit.css')>header.indexOf('acadme-finance-reports.css'),'Audit stylesheet load order incorrect');
assert.ok(pkg.includes('"test:acadme-system-audit-ui": "node tests/acadme-system-audit-ui.test.js"'),'Test script missing');
const tokens=new Set([...read('public/css/acadme-tokens.css').matchAll(/(--acm-[\\w-]+)\\s*:/g)].map(m=>m[1]));
for(const m of css.matchAll(/var\\((--acm-[\\w-]+)/g))assert.ok(tokens.has(m[1]),'Undefined token '+m[1]);
for(const field of ['log.timestamp','log.last_name','log.first_name','log.staff_id','log.module','log.action','log.details','log.ip_address','logs.forEach','No logs available yet.','window.print()'])assert.ok(page.includes(field),'Audit output contract missing '+field);
for(const v of ['audit-action-success','audit-action-login','audit-action-default','@media(max-width:760px)','@media print','size:A4 landscape'])assert.ok(css.includes(v),'Audit presentation rule missing '+v);
console.log('AcadMe System Audit UI source checks passed.');
