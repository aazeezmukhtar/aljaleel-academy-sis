'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8');
const controller = read('controllers/studentController.js');
const routes = read('routes/studentRoutes.js');
const profile = read('views/students/view.ejs');
const edit = read('views/students/edit.ejs');
const departure = read('views/students/departure.ejs');
assert.match(routes, /router\.get\('\/departure\/:id', isAdmin, studentController\.getStudentDeparturePage\)/);
assert.match(routes, /router\.post\('\/departure\/:id', isAdmin, studentController\.recordStudentDeparture\)/);
assert.match(controller, /eventType: departureType/);
assert.match(controller, /await db\.transaction\(async client =>/);
assert.match(controller, /UPDATE students SET status = 'withdrawn', current_class_id = NULL/);
assert.match(controller, /historyAvailable/);
assert.match(profile, /Enrollment & Movement History/);
assert.match(profile, /Transfer to another school/);
assert.match(departure, /id="departureScope"/);
assert.match(departure, /departure_scope:/);
assert.match(controller, /departureScope !== 'all'/);
assert.match(controller, /isReenrollment/);
assert.match(profile, /Re-enroll Student/);
assert.match(edit, /Assigning a class below will automatically re-enroll this student as ACTIVE/);
console.log('[student-departure-ui] Admin departure routes, section scope, re-enrollment, lifecycle guard, timeline and required departure fields passed.');
